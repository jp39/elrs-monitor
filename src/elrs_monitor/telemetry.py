"""ELRS 4.1 SX1280 downlink layout and RX TOCK scheduling (receive only).

Direction cannot be inferred from type bits: RC and LINKSTATS both use type 0.
The RX increments nonce at TOCK, hops, then transmits. TOCK follows the prior
uplink's RXdone by max(interval - 2*firmware_TOA, 200us).
"""

# ExpressLRS src/src/common.cpp, SX1280 ExpressLRS_AirRateRFperf TOA, microseconds.
TOA_US = {'50Hz':10798, '100Hz Full':7605, '150Hz':5871,
          '250Hz':3300, '333Hz Full':2374, '500Hz':1507}
DENOMINATORS = (1,128,64,32,16,8,4,2)


def downlink_offset(profile):
    toa = TOA_US[profile.name]/1e6
    return toa+max(profile.interval-2*toa,.0002)-profile.interval


def link_details(sync):
    denominator = DENOMINATORS[sync['telemetry_ratio_code']]
    return dict(link_mode=sync['link_mode'],telemetry_denominator=denominator,
                telemetry_ratio='off' if denominator==1 else f'1:{denominator}')


def decode_downlink(packet):
    """Decode only after identity-seeded CRC, time, nonce and RF direction gates.

    Sensor/MAVLink stubborn-transport fragments remain raw; no inferred sensor
    values or transport acknowledgements are generated by this listener.
    """
    full = len(packet)==13
    index = packet[0]>>3 if full else packet[1]&127
    ack = bool(packet[0]&4) if full else bool(packet[1]&128)
    payload = packet[1:11] if full else packet[2:7]
    result = dict(kind='data_fragment',package_index=index,stubborn_ack=ack)
    if packet[0]&3 == 0:
        a,b,lq,snr = payload[:4]
        if lq&127 > 100:
            raise ValueError('Invalid receiver link quality')
        result.update(kind='link_statistics',
                      uplink_rssi_1_dbm=-(a&127) if a&127 else None,
                      uplink_rssi_2_dbm=-(b&127) if b&127 else None,
                      active_antenna=a>>7,model_match=bool(b&128),
                      uplink_lq_percent=lq&127,true_diversity_available=bool(lq&128),
                      uplink_snr_db=(snr if snr<128 else snr-256)/4)
        payload = payload[4:]
    result['payload_hex'] = payload.hex()
    return result
