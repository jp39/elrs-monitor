"""Packet regression tests, including a CRC-valid packet from the capture."""
import unittest
import numpy as np
from elrs_monitor.profiles import get_profile
from elrs_monitor.protocol import (CODEBOOK, WHITENING, crc14, decode_long_interleaver,
                            decode_rc, decode_sync, validate_crc)

GOLDEN_BINS = [46,55,2,47,55,47,46,7,27,44,25,16,63,39,24,10,16,57,62,25,3,39]
GOLDEN_PACKET = bytes.fromhex('26a0811b2f5fe78f')


def encode_for_test(data, flip_bits=()):
    white = [d^w for d,w in zip(data, WHITENING)]
    nibbles = [n for b in white for n in (b & 15, b >> 4)]
    words = CODEBOOK[nibbles]
    bits = ((words[None, :] >> np.arange(7,-1,-1)[:, None]) & 1).ravel()
    for bit in flip_bits:
        bits[bit] ^= 1
    stream = np.r_[bits, np.zeros(4,dtype=int)].reshape(22,6)
    g = np.sum(stream*(2**np.arange(6))[None,:],axis=1)
    binary = g.copy()
    for shift in (1,2,4):
        binary ^= binary >> shift
    return ((binary+1) % 64).tolist()


class PacketTests(unittest.TestCase):
    def test_capture_regression(self):
        packet, corrections = decode_long_interleaver(GOLDEN_BINS)
        self.assertEqual(packet, GOLDEN_PACKET)
        self.assertEqual(corrections, 0)
        # Independently observed packet CRC: 0x098f, initializer 0x5bd3.
        self.assertTrue(validate_crc(packet, 0x5bd3))
        sync = decode_sync(packet)
        self.assertEqual(sync['rate_enum'], 27)
        self.assertEqual(sync['nonce'], 129)
        self.assertTrue(sync['hybrid'])

    def test_physical_50hz_wide_packet_regression(self):
        # Real SF8 symbols from the 20-second 50Hz/Wide diagnostic capture.
        # This is not generated by the synthetic encoder.
        bins=[197,193,97,213,145,165,53,185,216,56,51,145,213,213,49,32,52,253]
        packet,corrections=decode_long_interleaver(bins,1,get_profile('50Hz'))
        self.assertEqual(packet,bytes.fromhex('b8000218c07f20c2'))
        self.assertEqual(corrections,0)
        self.assertTrue(validate_crc(packet,0x5bd3,74))
        rc=decode_rc(packet,'Wide',74)
        self.assertEqual(rc['channels_raw10'],[512,512,1,511])
        self.assertEqual(rc['auxiliary_value'],32)
        self.assertEqual(rc['auxiliary_value_bits'],6)

    def test_roundtrip(self):
        rng = np.random.default_rng(10)
        for _ in range(100):
            data = rng.integers(0,256,8,dtype=np.uint8).tobytes()
            bins = encode_for_test(data)
            self.assertEqual(decode_long_interleaver(bins), (data, 0))
            self.assertEqual(decode_long_interleaver([(-v)%64 for v in bins], -1), (data, 0))

    def test_one_bit_correction(self):
        bins = encode_for_test(GOLDEN_PACKET, [10])
        self.assertEqual(decode_long_interleaver(bins), (GOLDEN_PACKET, 1))

    def test_two_bit_rejection(self):
        # Bits 0 and 16 belong to the same codeword in the long interleaver.
        with self.assertRaises(ValueError):
            decode_long_interleaver(encode_for_test(GOLDEN_PACKET, [0,16]))

    def test_crc_failure(self):
        changed = bytearray(GOLDEN_PACKET)
        changed[2] ^= 1
        self.assertFalse(validate_crc(changed, 0x5bd3))
        self.assertFalse(validate_crc(GOLDEN_PACKET, 0x5bd2))
        self.assertFalse(validate_crc(GOLDEN_PACKET, 0x5bd3, nonce=1))

    def test_crc_matches_reference_table_algorithm(self):
        # ELRS src/lib/CRC/crc.cpp's table recurrence, independently of bitwise path.
        table=[]
        for i in range(256):
            crc=i<<6
            for _ in range(8):
                crc=((crc<<1)^(0x2e57 if crc&0x2000 else 0)) & 0xffff
            table.append(crc)
        rng=np.random.default_rng(40)
        for _ in range(100):
            data=rng.integers(0,256,7,dtype=np.uint8).tobytes()
            init=int(rng.integers(0,65536))
            crc=init
            for b in data:
                crc=((crc<<8)^table[((crc>>6)^b)&255]) & 0xffff
            self.assertEqual(crc14(data,init),crc&0x3fff)

    def test_rc_unpack(self):
        channels=[1,512,1023,30]
        packed=sum(v<<(10*i) for i,v in enumerate(channels))
        p=bytes([0])+packed.to_bytes(5,'little')+bytes([0x80 | (3<<3) | 5,0])
        rc=decode_rc(p)
        self.assertEqual(rc['channels_raw10'],channels)
        self.assertTrue(rc['armed'])
        self.assertEqual(rc['auxiliary_channel'],5)
        self.assertEqual(rc['auxiliary_value'],5)


if __name__ == '__main__':
    unittest.main()
